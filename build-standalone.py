#!/usr/bin/env python3
"""Builds dist/mil-draft.html: one self-contained file (server logic runs in the browser, state in localStorage)."""
import re, os, json
root = os.path.dirname(os.path.abspath(__file__))
rd = lambda p: open(os.path.join(root, p), encoding='utf-8').read()
srv = rd('server.js')

def between(a, b):
    i = srv.index(a); j = srv.index(b, i)
    return srv[i:j]

users_seed = between('// ---------- users', 'let state;')
draft = between('// ---------- draft logic', '// presence:')
preplay = between('// pre-play the draft', 'let lastBot')

local = """// In-browser replacement for server.js (generated by build-standalone.py)
const LocalServer = (function () {
const C = CONFIG;
const KEY = 'mil-draft-state-v5';
const CLOCK_SECONDS = 60, BOT_DELAY_MS = 1000;
""" + users_seed + """
let state = null;
function load() { try { const s = JSON.parse(localStorage.getItem(KEY)); return s && s.schema === 5 ? s : null; } catch (e) { return null; } }
function persist() { try { localStorage.setItem(KEY, JSON.stringify(state)); } catch (e) { /* storage unavailable */ } }
const L = { onChange: null };
function save() { state.version++; persist(); if (L.onChange) L.onChange(); }
""" + draft + """
const anyHuman = (k) => !!(L.me && L.me.role === 'שלישות' && L.me.corps === k);
const humanUnit = (k, u) => anyHuman(k) && L.me.unit === u;
""" + preplay + """
state = load();
if (!state) { state = freshState(); Object.keys(C.corps).forEach(playUntilMine); persist(); }

setInterval(() => {
  const fresh = load(); if (fresh && fresh.version > state.version) { state = fresh; if (L.onChange) L.onChange(); }
  Object.keys(C.corps).forEach((k) => {
    const cst = state.corps[k], slot = orderOf(k)[cst.picks.length];
    if (!slot || !anyHuman(k)) return;
    const waited = Date.now() - cst.turnStartedAt, human = humanUnit(k, slot.u);
    if ((!human && waited >= BOT_DELAY_MS) || (human && waited >= CLOCK_SECONDS * 1000)) { const c = chooseFor(k, slot.u); if (c) doPick(k, slot.u, c.id, true); }
  });
}, 500);
window.addEventListener('storage', (e) => { if (e.key === KEY) { const f = load(); if (f) { state = f; if (L.onChange) L.onChange(); } } });

const num = (v) => { if (v === '' || v == null) return null; const n = Number(String(v).replace(',', '.')); return isFinite(n) ? n : null; };
L.config = () => ({ roles: C.ROLES, corps: C.corps, users: USERS, words: C.WORDS, MEDS: C.MEDS, RECS: C.RECS });
L.snapshot = () => { const uid = L.me && L.me.id, o = { version: state.version, serverNow: Date.now(), clockSeconds: CLOCK_SECONDS, corps: {}, log: state.log.slice(-60).reverse() }; Object.keys(C.corps).forEach((k) => { const f = state.corps[k].favs || {}; o.corps[k] = Object.assign({}, state.corps[k], { favs: uid && f[uid] ? { [uid]: f[uid] } : {} }); }); return JSON.parse(JSON.stringify(o)); };
L.handle = function (p, userId, b) {
  const user = userById(userId); L.me = user;
  if (!user) throw new Error('לא מחובר');
  const k = b.corps;
  const needCorps = () => { if (!C.corps[k]) throw new Error('חיל לא מוכר'); };
  const canView = () => { if (C.ROLES[user.role].scope !== 'all' && user.corps !== k) throw new Error('אין הרשאה לחיל זה'); };
  if (p === 'pick') { needCorps(); if (!canDo(user, 'pick', k)) throw new Error('רק שלישות היחידה יכולה לבחור'); doPick(k, user.unit, b.id, false); return { ok: true }; }
  if (p === 'eval') {
    needCorps(); canView();
    if (!canDo(user, 'eval', k)) throw new Error('רק מגבש/ת מזינ/ה התרשמות');
    const c = state.corps[k].cands.find((x) => x.id === b.id); if (!c) throw new Error('מועמד לא נמצא');
    if (c.group !== user.group) throw new Error('המועמד אינו בצוות שלך');
    applyEval(cfg(k), c, b, user.title);
    state.log.push({ ts: Date.now(), corps: k, text: user.title + ' הזינ/ה התרשמות על ' + c.name });
    save(); return { ok: true };
  }
  if (p === 'eval-bulk') {
    needCorps(); if (!canDo(user, 'evalbulk', k)) throw new Error('אין הרשאה להעלות נתוני מגבש');
    const cf = cfg(k), cst = state.corps[k], isEv = user.role === 'מגבש/ת', grp = isEv ? user.group : parseInt(b.group, 10);
    let updated = 0, added = 0, skipped = 0, foreign = 0, notFound = 0;
    (b.rows || []).slice(0, 500).forEach((r) => {
      const c = cst.cands.find((x) => (r.id && x.id === String(r.id).trim()) || (r.name && x.name === String(r.name).trim()));
      if (c) { if (isEv && c.group !== user.group) { foreign++; return; } if (applyEval(cf, c, r, user.title)) updated++; else skipped++; return; }
      if (b.addNew && r.name && cf.roles.includes(r.role) && TEAMS.includes(grp)) { const nc = newCand(cf, cst, String(r.name).trim(), r.role, grp, 'מגבש'); applyEval(cf, nc, r, user.title); added++; } else notFound++;
    });
    state.log.push({ ts: Date.now(), corps: k, text: user.title + ' קלט/ה קובץ: ' + updated + ' עודכנו, ' + added + ' נוספו' });
    save(); return { ok: true, updated, added, skipped, foreign, notFound };
  }
  if (p === 'regroup') {
    needCorps(); if (!canDo(user, 'regroup', k)) throw new Error('אין הרשאה להעביר מועמדים בין צוותים');
    const c = state.corps[k].cands.find((x) => x.id === b.id); if (!c) throw new Error('מועמד לא נמצא');
    const g = parseInt(b.group, 10); if (!TEAMS.includes(g)) throw new Error('צוות לא תקין');
    if (user.role === 'מגבש/ת' && c.group !== user.group) throw new Error('המועמד אינו בצוות שלך');
    const from = c.group; c.group = g;
    state.log.push({ ts: Date.now(), corps: k, text: user.title + ' העביר/ה את ' + c.name + ' מצוות ' + from + ' לצוות ' + g });
    save(); return { ok: true };
  }
  if (p === 'thresholds') {
    needCorps(); if (!canDo(user, 'thresholds', k)) throw new Error('אין הרשאה');
    const ov = state.corps[k].units.find((u) => u.name === user.unit), th = {};
    cfg(k).stats.forEach((s) => { const v = num((b.th || {})[s.k]); if (v != null) th[s.k] = v; });
    ov.th = th; ov.noMed = !!b.noMed;
    if (b.quota) { const q = {}; cfg(k).roles.forEach((r) => { const n = Math.max(0, Math.min(9, parseInt((b.quota || {})[r], 10) || 0)); if (n) q[r] = n; }); ov.quota = q; }
    save(); return { ok: true };
  }
  if (p === 'import') {
    needCorps(); if (!canDo(user, 'import', k)) throw new Error('אין הרשאה לייבא מועמדים');
    const cf = cfg(k), cst = state.corps[k];
    let max = cst.cands.reduce((m, c) => Math.max(m, parseInt(c.id.slice(cf.prefix.length), 10) || 0), 0);
    const used = new Set(cst.cands.map((c) => c.name)); let added = 0, skipped = 0, updated = 0, notFound = 0;
    if (b.mode === 'update') {
      (b.rows || []).forEach((r) => { const c = cst.cands.find((x) => (r.id && x.id === String(r.id).trim()) || (r.name && x.name === String(r.name).trim())); if (!c) { notFound++; return; } if (applyUpdate(cf, c, r)) updated++; else skipped++; });
      state.log.push({ ts: Date.now(), corps: k, text: user.title + ' עדכנה ' + updated + ' מועמדים מקובץ' });
      save(); return { ok: true, updated, skipped, notFound };
    }
    (b.rows || []).forEach((r) => {
      const name = String(r.name || '').trim();
      if (!name || used.has(name) || !cf.roles.includes(r.role)) { skipped++; return; }
      used.add(name); max++;
      const stats = {}; cf.stats.forEach((s) => { stats[s.k] = num((r.stats || {})[s.k]); });
      const med = C.MEDS.includes(r.med) ? r.med : C.MEDS[0];
      cst.cands.push({ id: cf.prefix + max, name, role: r.role, lv: cf.traits.map(() => 1), stats, rec: C.RECS.includes(r.rec) ? r.rec : null, med, profile: num(r.profile) || (med === C.MEDS[0] ? 97 : 72), area: '—', pref: '—', wish: { role: '', units: [], combat: null }, group: 1 + (max % 4), skills: cf.skills[r.role] || [], obs: '', summary: '', evaluated: false, source: 'ייבוא' });
      applyUpdate(cf, cst.cands[cst.cands.length - 1], { motivation: r.motivation, combat: r.combat });
      added++;
    });
    state.log.push({ ts: Date.now(), corps: k, text: user.title + ' ייבאה ' + added + ' מועמדים' });
    save(); return { ok: true, added, skipped };
  }
  if (p === 'baseline') {
    needCorps(); if (!canDo(user, 'import', k)) throw new Error('אין הרשאה להעלות נתוני ייחוס');
    const rows = cleanBaseline(cfg(k), b.rows); if (!rows.length) throw new Error('לא נמצאו שורות תקינות בקובץ (בדקו את עמודת התפקיד)');
    state.corps[k].baseline = { label: String(b.label || 'מחזור קודם').slice(0, 60), uploadedAt: Date.now(), by: user.title, rows };
    state.log.push({ ts: Date.now(), corps: k, text: user.title + ' העלתה נתוני ייחוס (' + rows.length + ' שורות)' });
    save(); return { ok: true, count: rows.length, skipped: (b.rows || []).length - rows.length };
  }
  if (p === 'baseline-clear') { needCorps(); if (!canDo(user, 'import', k)) throw new Error('אין הרשאה'); delete state.corps[k].baseline; save(); return { ok: true }; }
  if (p === 'fav') {
    needCorps(); if (!canDo(user, 'fav', k)) throw new Error('אין הרשאה לסמן מועדפים');
    const cst = state.corps[k]; if (!cst.cands.some((x) => x.id === b.id)) throw new Error('מועמד לא נמצא');
    cst.favs = cst.favs || {}; const set = new Set(cst.favs[user.id] || []); if (b.on) set.add(b.id); else set.delete(b.id); cst.favs[user.id] = Array.from(set);
    save(); return { ok: true };
  }
  if (p === 'undo') { needCorps(); if (!canDo(user, 'undo', k)) throw new Error('אין הרשאה'); const cst = state.corps[k]; if (!cst.picks.length) throw new Error('אין בחירות לביטול'); const last = cst.picks.pop(); cst.turnStartedAt = Date.now(); state.log.push({ ts: Date.now(), corps: k, text: user.title + ' ביטל/ה את הבחירה של ' + last.unit }); save(); return { ok: true }; }
  if (p === 'reset') { needCorps(); if (!canDo(user, 'reset', k)) throw new Error('אין הרשאה'); state.corps[k].picks = []; playUntilMine(k); save(); return { ok: true }; }
  if (p === 'advance') {
    needCorps(); if (!canDo(user, 'advance', k)) throw new Error('אין הרשאה');
    const cst = state.corps[k], order = orderOf(k);
    const target = b.steps ? Math.min(order.length, cst.picks.length + (b.steps | 0)) : Math.max(0, Math.min(4, b.rounds | 0)) * cfg(k).units.length;
    if (target < cst.picks.length) cst.picks = cst.picks.slice(0, target);
    while (cst.picks.length < target) { const slot = order[cst.picks.length]; const c = chooseFor(k, slot.u); if (!c) break; doPick(k, slot.u, c.id, true); }
    cst.turnStartedAt = Date.now(); save(); return { ok: true };
  }
  if (p === 'factory-reset') { if (!canDo(user, 'factory', null)) throw new Error('רק מנהל/ת מערכת יכול/ה לאפס את המערכת'); L.factoryReset(); return { ok: true }; }
  throw new Error('פעולה לא מוכרת');
};
L.factoryReset = () => { state = freshState(); Object.keys(C.corps).forEach(playUntilMine); save(); };
return L;
})();
"""

glue = """// Standalone glue: route api()/refresh()/SSE to the in-browser LocalServer
// confirm() is blocked in sandboxed viewers; actions are already explicit button clicks
try { window.confirm = () => true; } catch (e) { /* ignore */ }
async function api(path, body) {
  try { return LocalServer.handle(path, A.me ? A.me.id : '', JSON.parse(JSON.stringify(body || {}))); }
  catch (e) { toast(e.message, true); throw e; }
}
async function refresh() { A.S = LocalServer.snapshot(); A.skew = 0; }
function connectSSE() { LocalServer.me = A.me; LocalServer.onChange = async () => { await refresh(); rerender(true); }; }
(async function boot() {
  A.cfg = LocalServer.config();
  A.me = A.cfg.users.find((u) => u.id === localStorage.getItem('mil-user')) || null; LocalServer.me = A.me; await refresh();
  if (A.me) { connectSSE(); if (!route()) go(homeFor()); }
  render();
})();
"""

