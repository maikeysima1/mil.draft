#!/usr/bin/env python3
"""Builds dist/mil-draft.html: one self-contained file (server logic runs in the browser, state in localStorage)."""
import re, os, json
root = os.path.dirname(os.path.abspath(__file__))
rd = lambda p: open(os.path.join(root, p), encoding='utf-8').read()
srv = rd('server.js')

def between(a, b):
    i = srv.index(a); j = srv.index(b, i)
    return srv[i:j]

users_seed = between('// ---------- users', '// ---------- training model')
shared = between('// ---------- training model', '// ---------- end shared')

local = """// In-browser replacement for server.js (generated by build-standalone.py)
const LocalServer = (function () {
const C = CONFIG;
const KEY = 'mil-training-state-v8';
""" + users_seed + shared + """
let state = null;
function load() { try { const s = JSON.parse(localStorage.getItem(KEY)); return s && s.schema === SCHEMA ? s : null; } catch (e) { return null; } }
function persist() { try { localStorage.setItem(KEY, JSON.stringify(state)); } catch (e) { /* storage unavailable */ } }
const L = { onChange: null };
function save() { state.version++; persist(); if (L.onChange) L.onChange(); }
state = load();
if (!state) { state = freshState(); persist(); }
window.addEventListener('storage', (e) => { if (e.key === KEY) { const f = load(); if (f) { state = f; if (L.onChange) L.onChange(); } } });
L.config = () => ({ orgs: C.ORGS, roles: C.ROLES, TR: C.TR, TARGETS: C.TARGETS, corps: C.corps, users: USERS, words: C.WORDS, MEDS: C.MEDS, RECS: C.RECS });
L.snapshot = () => makeSnapshot(L.me && L.me.id);
L.handle = function (p, userId, b) { const user = userById(userId); L.me = user; if (!user) throw new Error('לא מחובר'); return apiHandle(p, b, user); };
return L;
})();
"""

glue = """// Standalone glue: route api()/refresh()/SSE to the in-browser LocalServer
// confirm() is blocked in sandboxed viewers; actions are already explicit button clicks
try { window.confirm = () => true; } catch (e) { /* ignore */ }
async function api(path, body) {
  try { return LocalServer.handle(path, A.me ? A.me.id : '', JSON.parse(JSON.stringify(body || {}))); }
  catch (e) { toast(e.message, true); throw e; }
}
async function refresh() { A.S = LocalServer.snapshot(); A.skew = 0; }
function connectSSE() { LocalServer.me = A.me; LocalServer.onChange = async () => { await refresh(); rerender(true); }; }
(async function boot() {
  A.cfg = LocalServer.config();
  A.me = A.cfg.users.find((u) => u.id === localStorage.getItem('mil-user')) || null; LocalServer.me = A.me; await refresh();
  if (A.me) { connectSSE(); if (!route()) go(homeFor()); }
  render();
})();
"""

cfgjs = rd('config.js')
cfg_wrapped = "const CONFIG = (function () { const module = { exports: {} };\n" + cfgjs + "\nreturn module.exports; })();\n"
xlsx = rd('public/xlsx.min.js')
SHIM = '''<script>try{localStorage.getItem('x')}catch(e){var _m={};Object.defineProperty(window,'localStorage',{value:{getItem:function(k){return k in _m?_m[k]:null},setItem:function(k,v){_m[k]=String(v)},removeItem:function(k){delete _m[k]}}})}</script>\n'''
def js(s): return s.replace('</script', '<\\/script')

html = """<!DOCTYPE html>
<html lang="he" dir="rtl">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"><meta name="theme-color" content="#0F1B35"><link rel="manifest" href="manifest.webmanifest"><link rel="apple-touch-icon" href="icons/apple-touch-icon.png"><link rel="icon" type="image/png" sizes="192x192" href="icons/icon-192.png"><meta name="apple-mobile-web-app-capable" content="yes"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-title" content="MIL-DRAFT"><meta name="apple-mobile-web-app-status-bar-style" content="black-translucent"><title>MIL-DRAFT</title>
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link href="https://fonts.googleapis.com/css2?family=Heebo:wght@400;500;600;700;800;900&display=swap" rel="stylesheet">
<style>""" + rd('public/style.css') + """</style></head>
<body><div id="app"></div><div id="toast" role="status" aria-live="polite"></div>
"""+SHIM+"""<script>""" + js(xlsx) + """</script>
<script>""" + js(cfg_wrapped) + """</script>
<script>""" + js(local) + """</script>
<script>""" + js(rd('public/core.js')) + """</script>
<script>""" + js(rd('public/train.js')) + """</script>
<script>""" + js(rd('public/screens.js')) + """</script>
<script>""" + js(glue) + """</script>
</body></html>
"""
os.makedirs(os.path.join(root, 'dist'), exist_ok=True)
out = os.path.join(root, 'dist', 'mil-draft.html')
open(out, 'w', encoding='utf-8').write(html)
print('wrote', out, len(html) // 1024, 'KB')
